"""Build, solve, interrogate, and document the public NRC piping benchmark.

Safe demo version: only the baseline PyMAPDL/PyVista figure is rendered.
All model-interrogation evidence is solver-derived and saved as JSON/text.
This avoids a Windows/VTK native access-violation seen when repeatedly
rendering selected meshes in the same MAPDL/PyVista session.
"""
from __future__ import annotations

import csv
import json
import os
from pathlib import Path

from ansys.mapdl.core import launch_mapdl

from model import build_model, compare_frequencies, save_baseline_database, solve_modal
from query_tools import connected_elements, elements_using_material, node_restraints, plot_model_with_bcs

HERE = Path(__file__).resolve().parent
OUT = HERE / "outputs"
RUN = HERE / ".mapdl_run"


def launch():
    RUN.mkdir(parents=True, exist_ok=True)
    kwargs = {
        "run_location": str(RUN),
        "jobname": "nrc_demo",
        "loglevel": "WARNING",
        "cleanup_on_exit": True,
    }
    executable = os.getenv("ANSYS_MAPDL_EXECUTABLE")
    if executable:
        kwargs["exec_file"] = executable
    return launch_mapdl(**kwargs)


def write_modal_csv(checks) -> None:
    with (OUT / "modal_check.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["mode", "reference_hz", "computed_hz", "difference_pct"])
        for c in checks:
            writer.writerow([c.mode, c.reference_hz, c.computed_hz, c.difference_pct])


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    mapdl = launch()

    try:
        print("[1/5] Building NRC piping benchmark...")
        build_model(mapdl)
        save_baseline_database(mapdl, RUN / "nrc_piping_baseline.db")

        summary = {
            "nodes": int(mapdl.mesh.n_node),
            "elements": int(mapdl.mesh.n_elem),
            "element_types": [int(v) for v in mapdl.mesh.etype.tolist()],
        }
        (OUT / "model_summary.json").write_text(
            json.dumps(summary, indent=2), encoding="utf-8"
        )

        print("[2/5] Saving baseline model/BC image...")
        plot_model_with_bcs(mapdl, OUT / "01_model_with_bcs.png")

        print("[3/5] Running deterministic model-interrogation queries...")
        q_connected = connected_elements(mapdl, 2)
        q_material = elements_using_material(mapdl, 1)
        q_bc = node_restraints(mapdl, 1)

        queries = {
            "what_elements_are_connected_to_node_2": q_connected.to_dict(),
            "which_elements_use_material_1": q_material.to_dict(),
            "show_restraints_at_node_1": q_bc.to_dict(),
        }
        (OUT / "query_results.json").write_text(
            json.dumps(queries, indent=2), encoding="utf-8"
        )

        # Write a compact terminal-friendly copy of the three answers as evidence.
        connected_list = ", ".join(map(str, q_connected.answer["elements"])) or "None"
        query_txt = (
            "MODEL INTERROGATION RESULTS\n"
            "===========================\n\n"
            "Q: What elements are connected to node 2?\n"
            f"A: {connected_list}\n"
            f"Evidence: {q_connected.evidence['mapdl_selection']}\n\n"
            "Q: Which elements use material 1?\n"
            f"A: {q_material.answer['count']} elements\n"
            f"Evidence: {q_material.evidence['mapdl_selection']}\n\n"
            "Q: Show restraints at node 1.\n"
            f"A: constrained = {q_bc.answer['constrained']}\n"
            "Evidence: DLIST output preserved in query_results.json\n"
        )
        (OUT / "query_summary.txt").write_text(query_txt, encoding="utf-8")

        print("[4/5] Solving first five modes...")
        frequencies = solve_modal(mapdl, 5)
        checks = compare_frequencies(frequencies)
        write_modal_csv(checks)

        print("[5/5] Writing evidence report...")
        max_abs_diff = max(abs(c.difference_pct) for c in checks)
        rows = "\n".join(
            f"| {c.mode} | {c.reference_hz:.3f} | {c.computed_hz:.3f} | {c.difference_pct:+.3f}% |"
            for c in checks
        )

        report = f"""# NRC Piping Demo - Generated Evidence

This report was generated by `run_demo.py` from a live MAPDL session.

## Model

- Nodes: **{summary['nodes']}**
- Elements: **{summary['elements']}**
- Public benchmark: NUREG/CR-1677, Volume 1, Problem 1

![MAPDL model with boundary conditions](01_model_with_bcs.png)

## Modal regression check

| Mode | NRC / Ansys reference (Hz) | This run (Hz) | Difference |
|---:|---:|---:|---:|
{rows}

Maximum absolute frequency difference: **{max_abs_diff:.3f}%**

## Model interrogation

### Prompt

> What elements are connected to node 2?

**Solver-derived answer:** {connected_list}

Evidence: `NSEL,S,NODE,,2` followed by `ESLN,S`.

### Prompt

> Which elements use material 1?

**Solver-derived element count:** {q_material.answer['count']}

Evidence: `ESEL,S,MAT,,1`.

### Prompt

> Show restraints at node 1.

**Solver-derived answer:** constrained = {q_bc.answer['constrained']}

The raw MAPDL `DLIST` rows are preserved in `query_results.json` rather than summarized by an LLM.

## Evidence files

- `01_model_with_bcs.png` - live PyMAPDL model rendering
- `model_summary.json` - model counts and element types
- `modal_check.csv` - reference-vs-computed modal regression
- `query_results.json` - structured solver-derived query evidence
- `query_summary.txt` - compact human-readable query summary

## Why this matters

The first public demo establishes the evidence chain used by later agent capabilities:

`question -> deterministic MAPDL query -> model fact/result -> saved evidence`

The LLM/MCP layer can later call these same tools, but it does not invent the model facts or numerical results.
"""
        (OUT / "demo_report.md").write_text(report, encoding="utf-8")

        print("Done.")
        print(f"Open: {OUT / 'demo_report.md'}")

    finally:
        try:
            mapdl.exit()
        except Exception:
            pass


if __name__ == "__main__":
    main()
